import { Router } from "express";
import * as c from "../controllers/controllers.js";
import { protect, allowRoles } from "../middleware/auth.js";

const router = Router();
router.post("/auth/register", c.register);
router.post("/auth/login", c.login);
router.get("/auth/me", protect, c.me);
router.put("/users/profile", protect, c.updateProfile);
router.put("/users/password", protect, c.changePassword);
router.get("/users/favourites", protect, c.listFavourites);
router.post("/users/favourites", protect, c.toggleFavourite);
router.put("/users/preferences", protect, c.savePreferences);
router.get("/places", c.listPlaces);
router.get("/places/:id", c.getPlace);
router.post("/places/:id/reviews", protect, c.addReview);
router.get("/recommendations", protect, c.getRecommendations);
router.get("/trips", protect, c.listTrips);
router.post("/trips", protect, c.createTrip);
router.put("/trips/:id", protect, c.updateTrip);
router.delete("/trips/:id", protect, c.deleteTrip);
router.get("/categories", c.categories);
router.get("/admin/stats", protect, allowRoles("admin"), c.adminStats);
router.get("/admin/users", protect, allowRoles("admin"), c.adminUsers);
router.patch("/admin/users/:id", protect, allowRoles("admin"), c.updateUserStatus);
router.delete("/admin/users/:id", protect, allowRoles("admin"), c.deleteUser);
router.post("/admin/places", protect, allowRoles("admin"), c.createPlace);
router.put("/admin/places/:id", protect, allowRoles("admin"), c.updatePlace);
router.delete("/admin/places/:id", protect, allowRoles("admin"), c.deletePlace);
router.post("/admin/categories", protect, allowRoles("admin"), c.createCategory);
router.delete("/admin/categories/:id", protect, allowRoles("admin"), c.deleteCategory);
export default router;
